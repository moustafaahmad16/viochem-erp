// Writes prisma/sqlite/schema.prisma, the desktop app's copy of prisma/schema.prisma for a SQLite file.
// The tables are the same; SQLite has no column sizes, so the @db.* attributes are dropped.
//
//   node scripts/sqlite-schema.mjs            write the schema
//   node scripts/sqlite-schema.mjs --check    fail if the SQLite migrations don't build the same tables
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "prisma/sqlite/schema.prisma");

const schema = readFileSync(path.join(root, "prisma/schema.prisma"), "utf8")
  .replace('provider = "postgresql"', 'provider = "sqlite"')
  // The Windows app runs the query engine built for Windows.
  .replace('provider = "prisma-client-js"', 'provider      = "prisma-client-js"\n  binaryTargets = ["native", "windows"]')
  .replace(/ *@db\.\w+(\([\d, ]+\))?/g, "");

mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, `// Generated by scripts/sqlite-schema.mjs from prisma/schema.prisma. Don't edit.\n\n${schema}`);

if (process.argv.includes("--check")) {
  const shadow = path.join(tmpdir(), `viochem-shadow-${process.pid}.db`);
  try {
    execFileSync(
      "npx",
      ["prisma", "migrate", "diff", "--from-migrations", "prisma/sqlite/migrations", "--to-schema-datamodel", out, "--shadow-database-url", `file:${shadow}`, "--exit-code"],
      { cwd: root, stdio: "inherit", env: { ...process.env, DATABASE_URL: `file:${shadow}` } },
    );
    console.log("The SQLite migrations match the schema.");
  } catch {
    console.error("The SQLite migrations don't match prisma/schema.prisma. Add one under prisma/sqlite/migrations (see README).");
    process.exitCode = 1;
  } finally {
    rmSync(shadow, { force: true });
  }
}
